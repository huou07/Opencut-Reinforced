void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  testWidgets('decodes a png frame', (tester) async {
    final codec = await ui.instantiateImageCodec(_png);
    final frame = await codec.getNextFrame();
    // ignore: avoid_print
    print('IMAGE_PROBE_OK ${frame.image.width}x${frame.image.height}');
    frame.image.dispose();
    codec.dispose();
  });
}
